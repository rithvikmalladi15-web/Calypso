import { useRef } from 'react'
import { Settings } from 'lucide-react'
import { usePreferences } from '../app/SettingsContext'
import { sources } from '../data/sourceRegistry'
import { limitations } from '../stores/experimentStore'
import { version } from '../simulation/engine'

export function WorkspaceSettings() {
  const context = usePreferences()
  const dialog = useRef<HTMLDialogElement>(null)
  const methodology = useRef<HTMLDialogElement>(null)
  if (!context) return null
  const {preferences,update,reset} = context
  const toggle = (label:string, key:'music'|'effects'|'mute'|'reducedMotion'|'grid') =>
    <label className="check">{label}<input type="checkbox" checked={preferences[key]} onChange={event=>update({[key]:event.target.checked})}/></label>
  const volume = (label:string,key:'volume'|'effectsVolume') =>
    <label className="field">{label} · {Math.round(preferences[key]*100)}%<input type="range" min="0" max="100" value={Math.round(preferences[key]*100)} onChange={event=>update({[key]:Number(event.target.value)/100})}/></label>
  const select = (label:string,key:'mood'|'animation'|'theme'|'units'|'quality',options:string[]) =>
    <label className="field">{label}<select value={preferences[key]} onChange={event=>update({[key]:event.target.value})}>{options.map(option=><option key={option} value={option}>{option==='Auto' ? 'Auto (reacts to simulation)' : option}</option>)}</select></label>
  return <>
    <button className="settings-trigger" aria-label="Settings" onClick={()=>dialog.current?.showModal()}><Settings size={17}/> Settings</button>
    <dialog ref={dialog} className="settings-drawer" aria-labelledby="settings-title" onClick={event=>{if(event.target===event.currentTarget)dialog.current?.close()}}>
      <div className="dialog-content">
        <div className="section-title"><h2 id="settings-title">Settings</h2><button aria-label="Close settings" onClick={()=>dialog.current?.close()}>×</button></div>
        <fieldset><legend>Audio</legend>
          {toggle('Music','music')}{volume('Music volume','volume')}{select('Music mood','mood',['Calm ocean','Deep space','Forest dawn','Auto'])}
          {toggle('Sound effects','effects')}{volume('Effects volume','effectsVolume')}{toggle('Master mute','mute')}
        </fieldset>
        <fieldset><legend>Visuals and units</legend>
          {select('Animation speed','animation',['Slow','Normal','Fast'])}{toggle('Reduced motion','reducedMotion')}{toggle('Show grid','grid')}
          {select('Theme','theme',['Light','Dark','System'])}{select('Units','units',['Metric','Imperial'])}{select('Chart quality','quality',['Low','Medium','High'])}
        </fieldset>
        <button onClick={()=>{if(window.confirm('Restore all settings to their defaults?'))reset()}}>Reset all settings to default</button>
      </div>
    </dialog>
    <button onClick={()=>methodology.current?.showModal()}>Data &amp; methodology</button>
    <dialog ref={methodology} className="methodology-dialog" aria-labelledby="methodology-title" onClick={event=>{if(event.target===event.currentTarget)methodology.current?.close()}}>
      <div className="dialog-content">
        <div className="section-title"><h2 id="methodology-title">Data &amp; methodology</h2><button aria-label="Close methodology" onClick={()=>methodology.current?.close()}>×</button></div>
        <p className="equation">∂C/∂t = −∇·(uC) + D∇²C + S − k max(C − Cfloor, 0)</p>
        <p>The spatial model uses a 32 × 18 grid and a 0.5-second finite-volume step. Ventilation, diffusion, and scrubber rates are illustrative.</p>
        <p>Sensor Lab model version {version}. The spatial workbench uses a separate transport solver.</p><p>{limitations}</p>
        <p>Automated checks cover conservation with no source or sink, finite concentrations, and reproducible threshold crossings. The model has not been empirically validated against cabin airflow measurements.</p>
        <p>CO₂ is reported in ppm. The demonstration threshold is a simulation rule. Sensor readings are generated by the model.</p>
        <ul>{sources.map(source=><li key={source.id}><a href={source.url} target="_blank" rel="noreferrer">{source.title}</a><p>{source.detail}</p></li>)}</ul>
        <a href="#/research" onClick={()=>methodology.current?.close()}>Review NASA sources</a>
      </div>
    </dialog>
  </>
}
